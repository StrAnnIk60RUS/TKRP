#!/usr/bin/env bash
# ==============================================================================
# Скрипт автоматизированного тестирования отказоустойчивости сервиса при сбое БД
# Курсовая работа: Раздел 3.2
# ==============================================================================
set -euo pipefail

HEALTH_URL="http://localhost/health"
API_HEALTH_URL="http://localhost:3001/health"
DB_CONTAINER="tkrp-db"

# Определяем доступный эндпоинт
TARGET_URL="${HEALTH_URL}"
if ! curl -s "${TARGET_URL}" > /dev/null 2>&1; then
  TARGET_URL="${API_HEALTH_URL}"
fi

echo "=========================================================="
echo " [ТЕСТ 3.2] Тестирование отказоустойчивости при сбое СУБД"
echo " Целевой эндпоинт: ${TARGET_URL}"
echo "=========================================================="

echo -e "\n--- ЭТАП 1: Проверка нормального состояния системы ---"
RES_1=$(curl -s -w "\nHTTP_STATUS:%{http_code}" "${TARGET_URL}")
echo "${RES_1}"

echo -e "\n--- ЭТАП 2: Имитация аварийной остановки контейнера СУБД ---"
docker stop "${DB_CONTAINER}"
echo "Контейнер ${DB_CONTAINER} остановлен."

sleep 2
echo -e "\n--- ЭТАП 3: Фиксация реакции приложения на недоступность БД ---"
RES_2=$(curl -s -w "\nHTTP_STATUS:%{http_code}" "${TARGET_URL}" || true)
echo "${RES_2}"

echo -e "\n--- ЭТАП 4: Перезапуск контейнера СУБД и восстановление сервиса ---"
docker start "${DB_CONTAINER}"
echo "Контейнер ${DB_CONTAINER} запущен. Ожидание готовности (healthcheck)..."

# Ожидание выхода СУБД в состояние healthy
until [ "$(docker inspect -f '{{.State.Health.Status}}' ${DB_CONTAINER} 2>/dev/null)" = "healthy" ]; do
  sleep 1
done

echo -e "\n--- ЭТАП 5: Проверка успешного автовосстановления связи ---"
RES_3=$(curl -s -w "\nHTTP_STATUS:%{http_code}" "${TARGET_URL}")
echo "${RES_3}"

echo -e "\n=========================================================="
echo "✅ ТЕСТ ОТКАЗОУСТОЙЧИВОСТИ УСПЕШНО ЗАВЕРШЕН!"
echo "Приложение корректно фиксирует деградацию и автоматически восстанавливает связь."
echo "=========================================================="
